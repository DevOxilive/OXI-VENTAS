export function getPurchaseReportToolbarConfig({
    branchName = '',
    search = '',
    filters = {},
    departments = [],
    categories = [],
    stockOptions = [],
    perPage = 25,
    total = 0,
} = {}) {
    return {
        icon: 'playlist_add',
        title: 'Mi lista de compra',
        subtitle: branchName,
        backButton: false,
        search,
        searchPlaceholder: 'Busca o escanea un producto',
        showSearch: true,
        compactFilters: true,
        showRecordsPerPage: true,
        recordsPerPage: Number(perPage),
        showCounter: false,
        filteredRecords: Number(total),
        totalRecords: Number(total),
        filters: [
            {
                key: 'departmentIds',
                label: 'Departamentos',
                placeholder: 'Todos los departamentos',
                type: 'multiselect',
                value: filters.departmentIds ?? [],
                options: departments,
                optionLabel: 'name',
                optionValue: 'id',
            },
            {
                key: 'categoryIds',
                label: 'Categorias',
                placeholder: 'Todas las categorias',
                type: 'multiselect',
                value: filters.categoryIds ?? [],
                options: categories,
                optionLabel: 'name',
                optionValue: 'id',
            },
            {
                key: 'stock',
                label: 'Stock',
                type: 'select',
                placeholder: 'Todo el stock',
                value: filters.stock ?? '',
                options: stockOptions,
            },
        ],
        actions: [],
        tabs: [],
    }
}
